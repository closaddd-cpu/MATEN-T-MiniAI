"""One-command, full-epoch training with data preparation and safe resumption.

This program runs only when invoked explicitly on a computer with Python and
PyTorch. GitHub itself does not provide a training GPU or start this process.
"""
from __future__ import annotations

from brand_guard import enforce_attribution
enforce_attribution()

import argparse
import json
import subprocess
import sys
from pathlib import Path

from build_datasets import FILES
from tools.verify_datasets import verify

ROOT = Path(__file__).resolve().parent
PER_SHARD = 100_000


def run(*args):
    print("BY MATEN/T |", " ".join(map(str, args)), flush=True)
    subprocess.run([sys.executable, *map(str, args)], cwd=ROOT, check=True)


def complete_data(folder: Path) -> bool:
    """Check metadata, shard presence and actual SHA-256/row counts."""
    manifest_file = folder / "manifest.json"
    if not manifest_file.is_file():
        return False
    try:
        manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return False
    domains = manifest.get("domains", {})
    if (manifest.get("expected_per_file") != PER_SHARD
            or manifest.get("total_records") != PER_SHARD * len(FILES)
            or set(domains) != set(FILES)):
        return False
    if not all((folder / (name + ".jsonl")).is_file() for name in FILES):
        return False
    try:
        return verify(folder)
    except (OSError, ValueError, KeyError):
        return False


def prepare_full_data() -> Path:
    primary = ROOT / "datasets"
    if complete_data(primary):
        return primary
    if any(primary.glob("*.jsonl")):
        # Preserve any custom, partial or previously modified datasets.
        # Build the complete synthetic set in a different directory.
        folder = ROOT / "datasets_full_100k"
    else:
        folder = primary
    if not complete_data(folder):
        print(f"BY MATEN/T | Building 94 full shards in {folder}", flush=True)
        # Only overwrite the designated autogenerated full folder.
        extra = ["--force"] if folder.name == "datasets_full_100k" else []
        run(ROOT / "build_datasets.py", "--count", PER_SHARD, "--out", folder, *extra)
        if not complete_data(folder):
            raise RuntimeError("Generated data failed integrity checks; training cancelled.")
    return folder


def parser():
    p = argparse.ArgumentParser(
        description="MATEN/T MiniAI — prepare data and run full uncapped training epochs"
    )
    p.add_argument("--device", choices=["auto", "cpu", "cuda", "mps"], default="auto")
    p.add_argument("--precision", choices=["auto", "fp16", "bf16", "fp32"], default="auto")
    p.add_argument("--epochs", type=int, default=1)
    p.add_argument("--sequence-length", type=int, default=1024)
    p.add_argument("--batch-size", type=int, default=1)
    p.add_argument("--grad-accum", type=int, default=8)
    p.add_argument("--save-every", type=int, default=500)
    p.add_argument("--output", default=str(ROOT / "checkpoints"))
    return p


def main(argv=None):
    opts = parser().parse_args(argv)
    if not 16 <= opts.sequence_length <= 6144:
        raise ValueError("Sequence length must be within 16..6144")
    if min(opts.epochs, opts.batch_size, opts.grad_accum, opts.save_every) < 1:
        raise ValueError("Epochs, batch size, grad accumulation and save interval must be positive")
    folder = prepare_full_data()
    tokenizer = ROOT / "tokenizer" / "tokenizer.model"
    if not tokenizer.is_file():
        run(ROOT / "miniai.py", "prepare", "--data", folder,
            "--samples-per-domain", 1000)

    output = Path(opts.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    cmd = [
        ROOT / "miniai.py", "train", "--data", folder, "--device", opts.device,
        "--precision", opts.precision, "--epochs", opts.epochs,
        "--sequence-length", opts.sequence_length, "--batch-size", opts.batch_size,
        "--grad-accum", opts.grad_accum, "--save-every", opts.save_every,
        "--output", output,
    ]
    checkpoint = output / "last.pt"
    if checkpoint.exists():
        print("BY MATEN/T | Resuming the latest trusted local checkpoint.", flush=True)
        cmd.extend(["--resume", checkpoint])
    else:
        print("BY MATEN/T | Starting complete training from random initialization.", flush=True)

    # Intentionally no --max-steps: train for all requested epochs.
    run(*cmd)


if __name__ == "__main__":
    main()
